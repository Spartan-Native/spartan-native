// Generates styles/contract/_palette-defaults.scss: the static palettes used
// when no runtime is present (plain CSS in a browser, server rendering, first paint).
//
//   npm run theme:palette
//
// It bundles the real derivePalette() with esbuild, so the CSS can never drift
// from the TypeScript.
import { buildSync } from 'esbuild';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const bundle = buildSync({
  entryPoints: [resolve(here, '../src/lib/palette/derive-palette.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  write: false,
});
const { derivePalette } = await import(
  'data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].text).toString('base64')
);

const ACCENT = '#0078d4';
// [skin, name, selector]. Variants carry their parent class too, so they outrank it.
const SKINS = [
  ['win', 'Windows 11', '.t-win'],
  ['w10', 'Windows 10', '.t-win.t-w10'],
  ['mac', 'macOS 26', '.t-mac'],
  ['macc', 'macOS 13–15', '.t-mac.t-macc'],
  ['gtk', 'GNOME · GTK 4', '.t-gtk'],
  ['qt', 'KDE Plasma · Breeze', '.t-qt'],
  ['cros', 'ChromeOS', '.t-cros'],
];
const kebab = (k) => k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const block = (selector, palette) =>
  `  ${selector} {\n${Object.entries(palette)
    .map(([k, v]) => `    --sn-color-${kebab(k)}: ${v};`)
    .join('\n')}\n  }\n`;

let out = `// GENERATED by scripts/generate-palette-defaults.mjs. Do not edit; run \`npm run theme:palette\`.
//
// Static palettes for accent ${ACCENT}. The runtime (applySpartanNative) overwrites
// these inline with the user's real accent; they make the theme work as plain CSS.

@layer spartan-native.tokens {
  // Fallback before any skin is applied: Windows 11, light
${block(':root', derivePalette({ skin: 'win', accent: ACCENT, scheme: 'light' }))}`;

for (const [skin, name, selector] of SKINS) {
  for (const scheme of ['light', 'dark']) {
    const sel = scheme === 'dark' ? `${selector}.dark` : selector;
    out += `\n  // ${name} · ${scheme}\n` + block(sel, derivePalette({ skin, accent: ACCENT, scheme }));
  }
}
out += '}\n';

const target = resolve(here, '../styles/contract/_palette-defaults.scss');
writeFileSync(target, out);
console.log('wrote', target);
